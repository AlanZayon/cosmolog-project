import { type NextRequest, NextResponse } from 'next/server';

import { isAutoGeneratedUsername } from '@/lib/auth/profile';
import { sanitizeRedirectPath } from '@/lib/auth/redirect';
import {
  OAUTH_CODE_VERIFIER_COOKIE,
  OAUTH_REDIRECT_COOKIE,
  OAUTH_STATE_COOKIE,
  clearOAuthCookies,
  setAuthCookies,
} from '@/lib/server/auth-cookies';
import { rustFetch, type RustAuthSession } from '@/lib/server/rust-api';

type RustProfile = {
  username: string;
};

export async function GET(request: NextRequest) {
  const origin = request.nextUrl.origin;
  const code = request.nextUrl.searchParams.get('code');
  const oauthError = request.nextUrl.searchParams.get('error_description')
    ?? request.nextUrl.searchParams.get('error');

  if (oauthError) {
    const response = NextResponse.redirect(
      new URL(`/login?error=${encodeURIComponent(oauthError)}`, origin),
    );
    clearOAuthCookies(response);
    return response;
  }

  const verifier = request.cookies.get(OAUTH_CODE_VERIFIER_COOKIE)?.value;
  const expectedState = request.cookies.get(OAUTH_STATE_COOKIE)?.value;
  const state = request.nextUrl.searchParams.get('state');
  const redirect = sanitizeRedirectPath(request.cookies.get(OAUTH_REDIRECT_COOKIE)?.value);

  if (!code || !verifier || !state || !expectedState || state !== expectedState) {
    const response = NextResponse.redirect(new URL('/login?error=oauth_invalid', origin));
    clearOAuthCookies(response);
    return response;
  }

  try {
    const redirectUri = new URL('/api/auth/google/callback', origin).toString();
    const session = await rustFetch<RustAuthSession>('/auth/oauth/exchange', {
      method: 'POST',
      body: JSON.stringify({
        auth_code: code,
        code_verifier: verifier,
        redirect_uri: redirectUri,
      }),
    });

    let destination = redirect;
    try {
      const profile = await rustFetch<RustProfile>('/profiles/me', {
        accessToken: session.access_token,
      });
      if (isAutoGeneratedUsername(profile.username)) {
        destination = '/profile?complete=1';
      }
    } catch {
      // Profile may not exist yet; continue with original redirect.
    }

    const response = NextResponse.redirect(new URL(destination, origin));
    setAuthCookies(response, session);
    clearOAuthCookies(response);
    return response;
  } catch {
    const response = NextResponse.redirect(new URL('/login?error=oauth_exchange_failed', origin));
    clearOAuthCookies(response);
    return response;
  }
}
