use sqlx::PgPool;
use time::{Duration, OffsetDateTime};
use uuid::Uuid;

use super::model::UserRecord;

const USER_COLUMNS: &str = "id, email, password_hash, email_verified_at, created_at, updated_at";

pub async fn find_user_by_email(
    pool: &PgPool,
    email: &str,
) -> Result<Option<UserRecord>, sqlx::Error> {
    sqlx::query_as::<_, UserRecord>(&format!(
        "SELECT {USER_COLUMNS} FROM users WHERE lower(email) = lower($1)"
    ))
    .bind(email)
    .fetch_optional(pool)
    .await
}

pub async fn find_user_by_id(
    pool: &PgPool,
    user_id: Uuid,
) -> Result<Option<UserRecord>, sqlx::Error> {
    sqlx::query_as::<_, UserRecord>(&format!("SELECT {USER_COLUMNS} FROM users WHERE id = $1"))
        .bind(user_id)
        .fetch_optional(pool)
        .await
}

pub async fn insert_user(
    pool: &PgPool,
    email: &str,
    password_hash: Option<&str>,
    email_verified: bool,
) -> Result<UserRecord, sqlx::Error> {
    sqlx::query_as::<_, UserRecord>(&format!(
        r#"
        INSERT INTO users (email, password_hash, email_verified_at)
        VALUES (lower($1), $2, CASE WHEN $3 THEN now() ELSE NULL END)
        RETURNING {USER_COLUMNS}
        "#
    ))
    .bind(email)
    .bind(password_hash)
    .bind(email_verified)
    .fetch_one(pool)
    .await
}

pub async fn set_email_verified(pool: &PgPool, user_id: Uuid) -> Result<(), sqlx::Error> {
    sqlx::query(
        "UPDATE users SET email_verified_at = COALESCE(email_verified_at, now()), updated_at = now() WHERE id = $1",
    )
    .bind(user_id)
    .execute(pool)
    .await?;
    Ok(())
}

/// Sets a new password and revokes every active refresh token for the user.
pub async fn set_password(
    pool: &PgPool,
    user_id: Uuid,
    password_hash: &str,
) -> Result<(), sqlx::Error> {
    let mut tx = pool.begin().await?;
    sqlx::query("UPDATE users SET password_hash = $2, updated_at = now() WHERE id = $1")
        .bind(user_id)
        .bind(password_hash)
        .execute(&mut *tx)
        .await?;
    sqlx::query(
        "UPDATE auth_refresh_tokens SET revoked_at = now() WHERE user_id = $1 AND revoked_at IS NULL",
    )
    .bind(user_id)
    .execute(&mut *tx)
    .await?;
    tx.commit().await
}

// --- Profiles -------------------------------------------------------------

/// Creates the profile row for a new user with a unique username
/// (mirrors the old Supabase `handle_new_user` trigger).
pub async fn insert_profile_for_user(
    pool: &PgPool,
    user_id: Uuid,
    desired_username: Option<&str>,
) -> Result<String, sqlx::Error> {
    let fallback = auto_username(user_id);
    let base = desired_username
        .map(sanitize_username)
        .filter(|name| !name.is_empty())
        .unwrap_or_else(|| fallback.clone());

    let mut candidate = base.clone();
    let mut suffix = 0u32;
    loop {
        let result = sqlx::query("INSERT INTO profiles (user_id, username) VALUES ($1, $2)")
            .bind(user_id)
            .bind(&candidate)
            .execute(pool)
            .await;
        match result {
            Ok(_) => return Ok(candidate),
            Err(sqlx::Error::Database(db)) if db.code().as_deref() == Some("23505") => {
                // Unique violation on user_id means the profile already exists.
                if db.constraint().is_some_and(|c| c.contains("user_id")) {
                    return Ok(candidate);
                }
                suffix += 1;
                if suffix > 50 {
                    candidate = fallback.clone();
                    if candidate == base {
                        candidate = format!("user_{}", Uuid::new_v4().simple());
                    }
                } else {
                    let trimmed: String = base.chars().take(47).collect();
                    candidate = format!("{trimmed}_{suffix}");
                }
            }
            Err(e) => return Err(e),
        }
    }
}

/// Matches the frontend `isAutoGeneratedUsername` pattern (`user_xxxxxxxx`).
pub fn auto_username(user_id: Uuid) -> String {
    format!("user_{}", &user_id.simple().to_string()[..8])
}

fn sanitize_username(raw: &str) -> String {
    raw.trim()
        .chars()
        .filter(|c| !c.is_control())
        .take(50)
        .collect::<String>()
        .trim()
        .to_string()
}

// --- Refresh tokens --------------------------------------------------------

pub async fn insert_refresh_token(
    pool: &PgPool,
    user_id: Uuid,
    token_hash: &str,
    ttl_days: i64,
) -> Result<(), sqlx::Error> {
    let expires_at = OffsetDateTime::now_utc() + Duration::days(ttl_days);
    sqlx::query(
        "INSERT INTO auth_refresh_tokens (user_id, token_hash, expires_at) VALUES ($1, $2, $3)",
    )
    .bind(user_id)
    .bind(token_hash)
    .bind(expires_at)
    .execute(pool)
    .await?;
    Ok(())
}

/// Atomically revokes a valid refresh token, returning its user (rotation).
pub async fn consume_refresh_token(
    pool: &PgPool,
    token_hash: &str,
) -> Result<Option<Uuid>, sqlx::Error> {
    sqlx::query_scalar::<_, Uuid>(
        r#"
        UPDATE auth_refresh_tokens
        SET revoked_at = now()
        WHERE token_hash = $1 AND revoked_at IS NULL AND expires_at > now()
        RETURNING user_id
        "#,
    )
    .bind(token_hash)
    .fetch_optional(pool)
    .await
}

pub async fn revoke_refresh_token(pool: &PgPool, token_hash: &str) -> Result<(), sqlx::Error> {
    sqlx::query(
        "UPDATE auth_refresh_tokens SET revoked_at = now() WHERE token_hash = $1 AND revoked_at IS NULL",
    )
    .bind(token_hash)
    .execute(pool)
    .await?;
    Ok(())
}

// --- Email tokens (confirmation / password reset) ---------------------------

pub async fn insert_email_token(
    pool: &PgPool,
    user_id: Uuid,
    purpose: &str,
    token_hash: &str,
    ttl_hours: i64,
) -> Result<(), sqlx::Error> {
    let expires_at = OffsetDateTime::now_utc() + Duration::hours(ttl_hours);
    sqlx::query(
        r#"
        INSERT INTO auth_email_tokens (user_id, purpose, token_hash, expires_at)
        VALUES ($1, $2, $3, $4)
        "#,
    )
    .bind(user_id)
    .bind(purpose)
    .bind(token_hash)
    .bind(expires_at)
    .execute(pool)
    .await?;
    Ok(())
}

/// Atomically marks a valid email token as used, returning its user.
pub async fn consume_email_token(
    pool: &PgPool,
    purpose: &str,
    token_hash: &str,
) -> Result<Option<Uuid>, sqlx::Error> {
    sqlx::query_scalar::<_, Uuid>(
        r#"
        UPDATE auth_email_tokens
        SET used_at = now()
        WHERE token_hash = $1 AND purpose = $2 AND used_at IS NULL AND expires_at > now()
        RETURNING user_id
        "#,
    )
    .bind(token_hash)
    .bind(purpose)
    .fetch_optional(pool)
    .await
}

// --- OAuth accounts ----------------------------------------------------------

pub async fn find_oauth_user(
    pool: &PgPool,
    provider: &str,
    provider_user_id: &str,
) -> Result<Option<Uuid>, sqlx::Error> {
    sqlx::query_scalar::<_, Uuid>(
        "SELECT user_id FROM oauth_accounts WHERE provider = $1 AND provider_user_id = $2",
    )
    .bind(provider)
    .bind(provider_user_id)
    .fetch_optional(pool)
    .await
}

pub async fn insert_oauth_account(
    pool: &PgPool,
    provider: &str,
    provider_user_id: &str,
    user_id: Uuid,
    email: Option<&str>,
) -> Result<(), sqlx::Error> {
    sqlx::query(
        r#"
        INSERT INTO oauth_accounts (provider, provider_user_id, user_id, email)
        VALUES ($1, $2, $3, lower($4))
        ON CONFLICT (provider, provider_user_id) DO NOTHING
        "#,
    )
    .bind(provider)
    .bind(provider_user_id)
    .bind(user_id)
    .bind(email)
    .execute(pool)
    .await?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::{auto_username, sanitize_username};
    use uuid::Uuid;

    #[test]
    fn auto_username_matches_frontend_pattern() {
        let id = Uuid::new_v4();
        let username = auto_username(id);
        assert!(username.starts_with("user_"));
        assert_eq!(username.len(), 13);
        assert!(username[5..].chars().all(|c| c.is_ascii_hexdigit()));
    }

    #[test]
    fn sanitize_strips_controls_and_limits_length() {
        assert_eq!(sanitize_username("  ana\u{0007} maria  "), "ana maria");
        let long = "x".repeat(80);
        assert_eq!(sanitize_username(&long).len(), 50);
        assert_eq!(sanitize_username("   "), "");
    }
}
